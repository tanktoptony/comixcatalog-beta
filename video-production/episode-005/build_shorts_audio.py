"""Episode 005 Shorts: the three standalone recordings laid end to end on one
clock (4 s apart), so one horizontal timeline (shorts-timeline.js) holds all
three and ShortClip cuts each one out by beat.

    .venv python -I episode-005/build_shorts_audio.py <voice dir> <tx dir>

Writes public/episode-005/audio/SHORTS_VOICE.wav and SHORTS_MUSIC.wav (Rollin
at 5 bed; no album audio in Shorts), episode-005/shorts.words.js and
episode-005/shorts-plan.json. Same levels as the episode.
"""
import json, os, re, subprocess, sys, wave
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
FF = os.path.join(ROOT, "node_modules", "@remotion", "compositor-win32-x64-msvc", "ffmpeg.exe")
AUD = os.path.join(ROOT, "public", "episode-005", "audio")
SR = 48000
voice_dir, tx_dir = sys.argv[1], sys.argv[2]

def decode(path, ch=1):
    wav = subprocess.run([FF, "-v", "error", "-i", path, "-ac", str(ch), "-ar", str(SR), "-c:a", "pcm_s16le", "-f", "wav", "-"],
                         check=True, capture_output=True).stdout
    d = wav.find(b"data")
    a = np.frombuffer(wav[d + 8:], dtype=np.int16).astype(np.float32) / 32768
    return a if ch == 1 else a[: len(a) // 2 * 2].reshape(-1, 2)

def write(path, x):
    if x.ndim == 1: x = np.stack([x, x], 1)
    with wave.open(path, "wb") as w:
        w.setnchannels(2); w.setsampwidth(2); w.setframerate(SR)
        w.writeframes((np.clip(x, -1, 1) * 32767).astype("<i2").tobytes())

def rms_db(x, pct=40):
    m = x.mean(1) if x.ndim == 2 else x
    f = m[: len(m) // 960 * 960].reshape(-1, 960)
    r = np.sqrt((f ** 2).mean(1) + 1e-12)
    loud = r[r > np.percentile(r, pct)]
    return 20 * np.log10(np.sqrt((loud ** 2).mean()))

files = sorted(f for f in os.listdir(voice_dir) if f.lower().startswith("short"))
t, parts, words, plan = 0.5, [], [], []
for k, f in enumerate(files):
    x = decode(os.path.join(voice_dir, f))
    x = x * 10 ** ((-13 - rms_db(x)) / 20)
    w = json.load(open(os.path.join(tx_dir, os.path.splitext(f)[0] + ".json")))
    end = min(len(x) / SR, w[-1]["e"] + 0.3)
    parts.append((t, x[: int(end * SR)]))
    for ww in w:
        words.append({"w": ww["w"], "s": round(t + ww["s"], 3), "e": round(t + ww["e"], 3), "short": k + 1})
    plan.append({"short": k + 1, "file": f, "at": round(t, 3), "end": round(t + end, 3)})
    t += end + 4.0
dur = t
voice = np.zeros(int(dur * SR) + SR, dtype=np.float32)
for at, seg in parts:
    voice[int(at * SR): int(at * SR) + len(seg)] += seg
peak = np.abs(voice).max()
if peak > 10 ** (-1.5 / 20): voice *= 10 ** (-1.5 / 20) / peak  # Shorts are short: plain gain is enough
write(os.path.join(AUD, "SHORTS_VOICE.wav"), voice)

bed = decode(os.path.join(AUD, "MUSIC_BED_FULL.wav"), 2)
bed = bed * 10 ** ((-27 - rms_db(bed, 30)) / 20)
music = np.zeros((len(voice), 2), dtype=np.float32)
for p in plan:
    a, b = int((p["at"] - 0.4) * SR), int((p["end"] + 2.6) * SR)
    seg = bed[: b - a]
    tt = np.arange(len(seg)) / SR
    g = np.clip(np.minimum(tt / 0.4, (len(seg) / SR - tt) / 1.2), 0, 1)[:, None]
    music[a: a + len(seg)] += seg * g
write(os.path.join(AUD, "SHORTS_MUSIC.wav"), music)

with open(os.path.join(HERE, "shorts.words.js"), "w", encoding="utf-8") as fh:
    fh.write("// Generated by build_shorts_audio.py.\nexport default " + json.dumps({"duration": round(dur, 3), "words": words}) + ";\n")
json.dump({"duration": round(dur, 3), "shorts": plan}, open(os.path.join(HERE, "shorts-plan.json"), "w"), indent=1)
print(plan, f"{dur:.1f}s")
