"""Episode 006 Shorts: the three standalone HeyGen recordings (build_voice.py)
laid end to end on one clock (4 s apart), so one horizontal timeline
(shorts-timeline.js) holds all three and ShortClip cuts each one out by beat.

    .venv python -I episode-006/build_shorts_audio.py

Writes public/episode-006/audio/SHORTS_VOICE.wav and SHORTS_MUSIC.wav (Rollin
at 5 bed), episode-006/shorts.words.js and episode-006/shorts-plan.json.
Same voice treatment as the episode (build_audio.py): light de-ess, speech at
-13 dBFS RMS, plain peak limiter at -1.5 dBFS.
"""
import json
from pathlib import Path

import numpy as np
import soundfile as sf

from build_audio import OUT, SR, deess, limit, speech_rms_db

HERE = Path(__file__).resolve().parent
SRC = Path.home() / "Desktop" / "YouTube" / "episode-006-assets" / "audio"
GAP = 4.0


def rms_db(x, pct=30):
    m = x.mean(1) if x.ndim == 2 else x
    f = m[: len(m) // 960 * 960].reshape(-1, 960)
    r = np.sqrt((f ** 2).mean(1) + 1e-12)
    loud = r[r > np.percentile(r, pct)]
    return 20 * np.log10(np.sqrt((loud ** 2).mean()))


def main():
    files = sorted(SRC.glob("short-*.wav"))
    assert len(files) == 3, files
    t, parts, words, plan = 0.5, [], [], []
    for k, f in enumerate(files):
        x, sr = sf.read(f, dtype="float32")
        assert sr == SR
        meta = json.loads(f.with_suffix(".words.json").read_text(encoding="utf-8"))
        end = min(len(x) / SR, meta["words"][-1]["e"] + 0.3)
        parts.append((t, x[: int(end * SR)]))
        words += [{"w": w["w"], "s": round(t + w["s"], 3), "e": round(t + w["e"], 3), "short": k + 1} for w in meta["words"]]
        plan.append({"short": k + 1, "file": f.name, "at": round(t, 3), "end": round(t + end, 3)})
        t += end + GAP
    dur = t
    voice = np.zeros(int(dur * SR) + SR, np.float32)
    for at, x in parts:
        i = int(at * SR)
        voice[i:i + len(x)] += x
    voice = deess(voice)
    voice = limit(voice * 10 ** ((-13 - speech_rms_db(voice)) / 20))
    sf.write(OUT / "SHORTS_VOICE.wav", np.stack([voice, voice], 1), SR, subtype="PCM_16")

    bed, _ = sf.read(OUT / "MUSIC_BED_FULL.wav", dtype="float32")
    bed = bed * 10 ** ((-27 - rms_db(bed)) / 20)
    music = np.zeros((len(voice), 2), np.float32)
    for p in plan:
        a, b = int((p["at"] - 0.4) * SR), int((p["end"] + 2.6) * SR)
        seg = bed[: b - a]
        tt = np.arange(len(seg)) / SR
        g = np.clip(np.minimum(tt / 0.4, (len(seg) / SR - tt) / 1.2), 0, 1)[:, None]
        music[a:a + len(seg)] += seg * g
    sf.write(OUT / "SHORTS_MUSIC.wav", music, SR, subtype="PCM_16")

    with open(HERE / "shorts.words.js", "w", encoding="utf-8") as fh:
        fh.write("// Generated by episode-006/build_shorts_audio.py. Do not edit by hand.\n")
        fh.write("export default " + json.dumps({"duration": round(dur, 3), "words": words}, separators=(",", ":")) + ";\n")
    (HERE / "shorts-plan.json").write_text(json.dumps({"duration": round(dur, 3), "shorts": plan}, indent=1) + "\n", encoding="utf-8")
    print(plan, f"{dur:.1f}s")


if __name__ == "__main__":
    main()
