"""Episode 007 Shorts: Tony's three standalone Shorts recordings (short 1/2/3.m4a)
laid end to end on one clock (4 s apart), so one horizontal timeline
(shorts-timeline.js) holds all three and ShortClip cuts each one out by beat.

    .venv python -I episode-007/build_shorts_audio.py

Each recording opens with a slate ("Short number one,"), which is dropped; the
spoken title after it ("Batman got replaced in the 90s.") stays as the hook.
Same voice treatment as the episode (build_audio.py): leveled to -13 dBFS
speech RMS, long pauses shortened to MAX_PAUSE, light de-ess, plain peak
limiter at -1.5 dBFS. Music: the Double Drift bed at -27 dB RMS under each.

Writes public/episode-007/audio/SHORTS_VOICE.wav and SHORTS_MUSIC.wav,
episode-007/shorts.words.js and episode-007/shorts-plan.json.
"""
import json

import numpy as np
import soundfile as sf

from build_audio import HERE, OUT, RAW, SR, VO_WORDS, decode_mono, deess, level, limit, load_words, vo_range

GAP = 4.0
# Slate words to drop per Short, and the word the Short then opens on.
SLATE = {1: (3, "Batman"), 2: (6, "Batman"), 3: (5, "Bruce")}


def rms_db(x, pct=30):
    m = x.mean(1) if x.ndim == 2 else x
    f = m[: len(m) // 960 * 960].reshape(-1, 960)
    r = np.sqrt((f ** 2).mean(1) + 1e-12)
    loud = r[r > np.percentile(r, pct)]
    return 20 * np.log10(np.sqrt((loud ** 2).mean()))


def main():
    t, parts, words, plan = 0.5, [], [], []
    for k in (1, 2, 3):
        audio = level(decode_mono(RAW / f"short {k}.m4a"))
        ws = load_words(VO_WORDS / f"short-{k}.words.js")
        skip, first = SLATE[k]
        assert ws[skip]["w"].strip(",.") == first, (k, ws[skip])
        x, kept = vo_range(audio, ws, ws[skip]["s"], 1e9, floor=ws[skip - 1]["e"] + 0.05)
        x = deess(x)
        parts.append((t, x))
        words += [{"w": w["w"], "s": round(t + w["s"], 3), "e": round(t + w["e"], 3), "short": k} for w in kept]
        end = t + len(x) / SR
        plan.append({"short": k, "file": f"short {k}.m4a", "at": round(t, 3), "end": round(end, 3)})
        t = end + GAP
    dur = t
    voice = np.zeros(int(dur * SR) + SR, np.float32)
    for at, x in parts:
        i = int(round(at * SR))
        voice[i:i + len(x)] += x
    voice = limit(voice)
    sf.write(OUT / "SHORTS_VOICE.wav", np.stack([voice, voice], 1), SR, subtype="PCM_16")

    bed, _ = sf.read(OUT / "MUSIC_BED_DOUBLE_DRIFT.wav", dtype="float32")
    bed = bed * 10 ** ((-27 - rms_db(bed)) / 20)
    music = np.zeros((len(voice), 2), np.float32)
    for p in plan:
        a, b = int((p["at"] - 0.4) * SR), int((p["end"] + 2.6) * SR)
        seg = bed[: b - a]
        tt = np.arange(len(seg)) / SR
        g = np.clip(np.minimum(tt / 0.4, (len(seg) / SR - tt) / 1.2), 0, 1)[:, None]
        music[a:a + len(seg)] += seg * g
    sf.write(OUT / "SHORTS_MUSIC.wav", music, SR, subtype="PCM_16")

    with open(HERE / "shorts.words.js", "w", encoding="utf-8") as fh:
        fh.write("// Generated by episode-007/build_shorts_audio.py. Do not edit by hand.\n")
        fh.write("export default " + json.dumps({"duration": round(dur, 3), "words": words}, separators=(",", ":")) + ";\n")
    (HERE / "shorts-plan.json").write_text(json.dumps({"duration": round(dur, 3), "shorts": plan}, indent=1) + "\n", encoding="utf-8")
    for p in plan:
        print(f"Short {p['short']}: {p['end'] - p['at']:.1f}s")


if __name__ == "__main__":
    main()
