"""Pixel size of every image in public/episode-007, for panel framing.

    python episode-007/build_sizes.py   -> episode-007/sizes.js
"""
import json
import os
from pathlib import Path

from PIL import Image

BASE = Path(__file__).resolve().parent.parent / "public" / "episode-007"
sizes = {}
for d in ["art", "covers", "screens"]:
    for p in sorted((BASE / d).rglob("*")):
        if p.suffix.lower() in (".jpg", ".jpeg", ".png", ".webp"):
            sizes[p.relative_to(BASE).as_posix()] = list(Image.open(p).size)
out = Path(__file__).resolve().parent / "sizes.js"
out.write_text("// Generated by episode-007/build_sizes.py. Do not edit by hand.\nexport default " + json.dumps(sizes, separators=(",", ":")) + ";\n", encoding="utf-8")
print(len(sizes), "images")
