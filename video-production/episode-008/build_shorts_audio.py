"""Episode 008 Shorts: the three HeyGen Short reads (build_voice.py, from
SHORTS.md, Tony OKed the words 2026-11-18) laid end to end on one clock (4 s
apart), so one timeline (shorts-timeline.js) holds all three and ShortClip
cuts each one out by beat. Same shape as episode-007/build_shorts_audio.py.

    .venv python -I episode-008/build_shorts_audio.py

Voice treatment matches the episode (build_audio.py): light de-ess, each
Short leveled to -13 dBFS speech RMS, plain peak limiter at -1.5 dBFS.
Music: the Double Drift bed at -27 dB RMS under each, as in Ep 007.

Writes public/episode-008/audio/SHORTS_VOICE.wav and SHORTS_MUSIC.wav,
episode-008/shorts.words.js and episode-008/shorts-plan.json.
"""
import json

import numpy as np
import soundfile as sf

from build_audio import HERE, OUT, SR, SRC, deess, limit, speech_rms_db

GAP = 4.0


def rms_db(x, pct=30):
    m = x.mean(1) if x.ndim == 2 else x
    f = m[: len(m) // 960 * 960].reshape(-1, 960)
    r = np.sqrt((f ** 2).mean(1) + 1e-12)
    loud = r[r > np.percentile(r, pct)]
    return 20 * np.log10(np.sqrt((loud ** 2).mean()))


def main():
    t, parts, words, plan = 0.5, [], [], []
    for k in (1, 2, 3):
        [wav] = SRC.glob(f"short-{k} - *.wav")
        x, sr = sf.read(wav, dtype="float32")
        assert sr == SR, (wav, sr)
        meta = json.loads(wav.with_suffix(".words.json").read_text(encoding="utf-8"))
        x = deess(x)
        x = limit(x * 10 ** ((-13 - speech_rms_db(x)) / 20))
        parts.append((t, x))
        words += [{"w": w["w"], "s": round(t + w["s"], 3), "e": round(t + w["e"], 3), "short": k} for w in meta["words"]]
        # The file carries 0.55 s of tail after the last chunk; the Short ends on its last word.
        end = t + meta["words"][-1]["e"] + 0.4
        plan.append({"short": k, "file": wav.name, "at": round(t, 3), "end": round(end, 3)})
        t = t + len(x) / SR + GAP
    dur = round(t, 3)
    voice = np.zeros(int(dur * SR) + SR, np.float32)
    for at, x in parts:
        i = int(round(at * SR))
        voice[i:i + len(x)] += x
    sf.write(OUT / "SHORTS_VOICE.wav", np.stack([voice, voice], 1), SR, subtype="PCM_16")

    bed, _ = sf.read(OUT / "MUSIC_BED_DOUBLE_DRIFT.wav", dtype="float32")
    bed = bed * 10 ** ((-27 - rms_db(bed)) / 20)
    music = np.zeros((len(voice), 2), np.float32)
    for p in plan:
        a, b = int((p["at"] - 0.4) * SR), int((p["end"] + 2.6) * SR)
        seg = bed[: b - a]
        tt = np.arange(len(seg)) / SR
        g = np.clip(np.minimum(tt / 0.4, (len(seg) / SR - tt) / 1.2), 0, 1)[:, None]
        music[a:a + len(seg)] += seg * g
    sf.write(OUT / "SHORTS_MUSIC.wav", music, SR, subtype="PCM_16")

    with open(HERE / "shorts.words.js", "w", encoding="utf-8") as fh:
        fh.write("// Generated by episode-008/build_shorts_audio.py. Do not edit by hand.\n")
        fh.write("export default " + json.dumps({"duration": dur, "words": words}, separators=(",", ":"), ensure_ascii=False) + ";\n")
    (HERE / "shorts-plan.json").write_text(json.dumps({"duration": dur, "shorts": plan}, indent=1) + "\n", encoding="utf-8")
    for p in plan:
        print(f"Short {p['short']}: {p['end'] - p['at']:.1f}s (+{2.6} end card)")
    print(f"voice speech {speech_rms_db(voice):.1f} dBFS RMS, peak {20 * np.log10(np.abs(voice).max()):.1f} dBFS")


if __name__ == "__main__":
    main()
