"""Stage Ep 008 art from Desktop/YouTube/episode-008-assets into
public/episode-008 (gitignored) and write episode-008/sizes.js.

    .venv python -I episode-008/stage_assets.py

covers/    ComicVine covers, flattened: lake-NN.jpg, sea-NN.jpg, lake-01-vNN.jpg
           (the 21 #1 variants), lake-NN-v.jpg (later issues' variant),
           lake-tpb-1/2.jpg, lake-deluxe.jpg, lake-fcbd.jpg
art/<set>/ DC preview pages (Comic Watch / Graphic Policy posts), long side
           capped at MAX px, PNG captures re-saved as JPEG
photos/    Wikimedia Commons photos (credits in photo-credits.json)
screens/   live ComixCatalog captures, plus 16:9 crops of the tall series pages
"""
import json
import re
import shutil
from pathlib import Path

from PIL import Image

HERE = Path(__file__).resolve().parent
SRC = Path.home() / "Desktop" / "YouTube" / "episode-008-assets"
OUT = HERE.parent / "public" / "episode-008"
MAX = 2600
RENAME = {"james-tynion-iv-and-alvaro-martinez-buen": "sea-announce", "meet-the-cast-of-the-nice-house-by-the-s": "sea-cast"}
# Tall series pages -> 1920x1080 crops on the "12 issues / Printable checklist" row and the cover grid.
TALL_CROPS = {"cc-series-sea-grid.png": ("cc-series-sea-tall.png", 830), "cc-series-lake-grid.png": ("cc-series-lake-tall.png", None)}

sizes = {}


def put(src, rel, cap=True):
    dst = OUT / rel
    dst.parent.mkdir(parents=True, exist_ok=True)
    im = Image.open(src)
    if cap and max(im.size) > MAX:
        im = im.convert("RGB")
        im.thumbnail((MAX, MAX), Image.LANCZOS)
        im.save(dst, quality=90)
    elif dst.suffix == ".jpg" and src.suffix.lower() == ".png":
        im.convert("RGB").save(dst, quality=92)
    else:
        shutil.copyfile(src, dst)
    sizes[rel] = list(Image.open(dst).size)


def main():
    for f in sorted((SRC / "covers").rglob("*.jpg")):
        m = re.match(r"(lake|sea|lake-tpb|lake-deluxe|lake-fcbd)-(\d\d)-(a|v\d\d)\.jpg", f.name)
        if not m:  # covers/other: other books named in the script, kept as named
            put(f, f"covers/{f.name}", cap=False)
            continue
        kind, n, v = m.groups()
        if kind == "lake-tpb":
            name = f"lake-tpb-{int(n)}.jpg"
        elif kind in ("lake-deluxe", "lake-fcbd"):
            name = f"{kind}.jpg"
        elif v == "a":
            name = f"{kind}-{n}.jpg"
        elif n == "01":
            name = f"{kind}-01-{v}.jpg"
        else:
            name = f"{kind}-{n}-v.jpg"
        put(f, f"covers/{name}", cap=False)
    for d in sorted(p for p in (SRC / "interiors").iterdir() if p.is_dir()):
        for f in sorted(d.iterdir()):
            if f.suffix.lower() not in (".jpg", ".jpeg", ".png"):
                continue
            stem = re.sub(r"[^a-z0-9]+", "-", f.stem.lower()).strip("-")[:40]
            put(f, f"art/{RENAME.get(d.name, d.name)}/{stem}.jpg")
    for f in sorted((SRC / "photos").glob("*.jpg")):
        put(f, f"photos/{f.name}")
    for f in sorted((SRC / "screens").glob("*.png")):
        put(f, f"screens/{f.name}", cap=False)
    for name, (tall, y) in TALL_CROPS.items():
        if y is None:
            continue
        im = Image.open(SRC / "screens" / tall)
        im.crop((0, y, 1920, y + 1080)).save(OUT / "screens" / name)
        sizes[f"screens/{name}"] = [1920, 1080]
    (HERE / "sizes.js").write_text("// Generated by episode-008/stage_assets.py: pixel sizes of staged art.\nexport default "
                                   + json.dumps(sizes, indent=0, sort_keys=True) + ";\n", encoding="utf-8")
    print(f"{len(sizes)} files staged into {OUT}")


if __name__ == "__main__":
    main()
