"""Stage Ep 009 art from Desktop/YouTube/episode-009-assets into
public/episode-009 (gitignored) and write episode-009/sizes.js.

    .venv python -I episode-009/stage_assets.py

covers/      IKSSE:3 (BOOM!, 2010-2011): iksse-NN.jpg, iksse-01-vNN.jpg (the #1
             variants: v01 is the "Convention exclusive limited to 500" cover),
             iksse-05-v.jpg (New York Comic Con 2010), iksse-09-v.jpg (C2E2
             exclusive limited to 300), iksse-ultimate.jpg (2012)
albums/      every Coheed album cover (from Part 2)
characters/  official character art (Coheed and Cambria Wiki), as in Ep 005
photos/      Wikimedia Commons photos, credits in photo-credits.json
screens/     live ComixCatalog captures (2026-11-17)
"""
import re
import shutil
from pathlib import Path

from PIL import Image

HERE = Path(__file__).resolve().parent
SRC = Path.home() / "Desktop" / "YouTube" / "episode-009-assets"
OUT = HERE.parent / "public" / "episode-009"
MAX = 2600

sizes = {}


def put(src, rel):
    dst = OUT / rel
    dst.parent.mkdir(parents=True, exist_ok=True)
    im = Image.open(src)
    if max(im.size) > MAX:
        im = im.convert("RGB")
        im.thumbnail((MAX, MAX), Image.LANCZOS)
        im.save(dst, quality=90)
    else:
        shutil.copyfile(src, dst)
    sizes[rel] = list(Image.open(dst).size)


def main():
    for f in sorted((SRC / "covers" / "iksse").glob("*.jpg")):
        m = re.match(r"iksse-(\d\d)-(a|v\d\d)\.jpg", f.name)
        if not m:
            continue
        n, v = m.groups()
        name = f"iksse-{n}.jpg" if v == "a" else (f"iksse-01-{v}.jpg" if n == "01" else f"iksse-{n}-v.jpg")
        put(f, f"covers/{name}")
    put(SRC / "covers" / "iksse-ultimate" / "iksse-ultimate-01-a.jpg", "covers/iksse-ultimate.jpg")
    for folder in ("albums", "characters", "photos", "screens", "lore"):
        for f in sorted((SRC / folder).iterdir()):
            if f.suffix.lower() in (".jpg", ".jpeg", ".png"):
                put(f, f"{folder}/{f.name}")
    lines = ["// Generated by episode-009/stage_assets.py: real pixel sizes of the staged art.", "export default {"]
    lines += [f'  "{k}": [{w}, {h}],' for k, (w, h) in sorted(sizes.items())]
    lines.append("};")
    (HERE / "sizes.js").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"staged {len(sizes)} files into {OUT}")


if __name__ == "__main__":
    main()
